/** Music level per frame: quieter (ducked) while the narrator speaks, fades in at the start. */
const MUSIC_LEVEL: number[] = (() => {
  const n = TIMELINE.durationInFrames;
  const speaking = new Array<number>(n).fill(0);
  for (const id of SENTENCE_ORDER) {
    const s = TIMELINE.sentences[id];
    for (let f = Math.max(0, s.from - 3); f < Math.min(n, s.to + 3); f++) speaking[f] = 1;
  }
  const level: number[] = [];
  let duck = 0;
  for (let f = 0; f < n; f++) {
    duck += (speaking[f] - duck) * (speaking[f] > duck ? 0.35 : 0.12); // fast attack, slow release
    const fadeIn = Math.min(1, f / 12);
    level.push(fadeIn * (0.13 - 0.055 * duck));
  }
  return level;
})();

